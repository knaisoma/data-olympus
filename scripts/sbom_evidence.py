#!/usr/bin/env python3
"""Per-artifact SBOM evidence for candidates (SDLC section 9, phase B step 4).

Every reusable candidate artifact gets its own SPDX 2.3 JSON SBOM, generated by
the pinned syft in rc-build.yml:

  wheel   the extracted wheel plus the runtime dependency closure exported from
          the candidate's uv.lock without the dev group
  sdist   the extracted sdist plus that same exported closure
  image   one document per platform manifest of the OCI index; its root
          package checksum is that platform manifest digest

The SBOM binding is the attestation subject: rc-publish-stage.yml signs each
document with the wheel or sdist SHA-256, or the platform manifest digest, as
subject. promote-release.yml verifies those attestations with the SPDX
predicate type and the pinned signer, and requires the signed predicate to be
byte-for-byte JSON-equal to the document stored as a candidate release asset.

Stage one runs candidate code, so its documents are untrusted input. This
module validates them with fixed rules and bounded reads, for the stage-one
receipt, for the stage-two verifier and again for promotion. It is stdlib only
because stage two and promotion run it without installing the project.

Commands:

  embed      stage one: validate the generated documents against the
             finalized release-provenance.json and add the receipt entries
             to it as "sboms" (release_artifacts.py stays unchanged)
  plan       promotion: check the downloaded documents against the candidate
             provenance and the raw registry index, and print one line per
             attestation to verify: "<subject> <document path> <subject digest>"
  match      promotion: require that one verified SPDX attestation of the
             subject carries exactly the stored document as its predicate
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import tarfile
from pathlib import Path
from typing import Any

SYFT_VERSION = "1.52.0"
GENERATOR = f"Tool: syft-{SYFT_VERSION}"
PREDICATE_TYPE = "https://spdx.dev/Document/v2.3"
SPDX_VERSION = "SPDX-2.3"
IMAGE = "ghcr.io/knaisoma/data-olympus"
PROJECT = "data-olympus"
PLATFORMS = ("linux/amd64", "linux/arm64")
SBOM_DIR = "sbom"
# actions/attest refuses an SBOM above 16 MiB (MAX_SBOM_SIZE_BYTES in its
# src/sbom.ts at the pinned v4.2.2); nothing larger can be signed.
SBOM_LIMIT = 16 * 1024 * 1024
INDEX_LIMIT = 4 * 1024 * 1024
ATTESTATION_LIMIT = 64 * 1024 * 1024
HEX = re.compile(r"[0-9a-f]{64}")
DIGEST = re.compile(r"sha256:[0-9a-f]{64}")
# Like release_record.ASSET: a leading letter or digit rules out "..", ".hidden".
NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]*")
OCI_INDEX = ("application/vnd.oci.image.index.v1+json",
             "application/vnd.docker.distribution.manifest.list.v2+json")
KINDS = ("wheel", "sdist", "image")


def require(condition: bool, message: str) -> None:
    """Fail closed. Messages are fixed strings, never untrusted input."""
    if not condition:
        raise ValueError(message)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def document_name(kind: str, subject: str) -> str:
    """wheel/sdist: '<file>.spdx.json'; image: 'image-<os>-<arch>.spdx.json'."""
    if kind == "image":
        require(subject in PLATFORMS, "unsupported image platform")
        return "image-" + subject.replace("/", "-") + ".spdx.json"
    require(kind in ("wheel", "sdist") and NAME.fullmatch(subject) is not None,
            "invalid SBOM subject")
    return subject + ".spdx.json"


def read_bounded(path: Path, limit: int) -> bytes:
    require(not path.is_symlink() and path.is_file(), "SBOM evidence must be a regular file")
    require(path.stat().st_size <= limit, "oversized SBOM evidence")
    with path.open("rb") as stream:
        data = stream.read(limit + 1)
    require(len(data) <= limit, "oversized SBOM evidence")
    return data


def parse_json(raw: bytes, message: str) -> Any:
    try:
        return json.loads(raw)
    except (ValueError, RecursionError):
        raise ValueError(message) from None


def _described_root(document: dict[str, Any]) -> dict[str, Any]:
    relationships = document.get("relationships")
    packages = document.get("packages")
    require(isinstance(relationships, list) and isinstance(packages, list),
            "SBOM lacks packages or relationships")
    assert isinstance(relationships, list) and isinstance(packages, list)
    roots = [r.get("relatedSpdxElement") for r in relationships if isinstance(r, dict)
             and r.get("spdxElementId") == "SPDXRef-DOCUMENT"
             and r.get("relationshipType") == "DESCRIBES"]
    require(len(roots) == 1 and isinstance(roots[0], str), "SBOM must describe one root")
    found = [p for p in packages if isinstance(p, dict) and p.get("SPDXID") == roots[0]]
    require(len(found) == 1, "SBOM root package missing")
    return found[0]


def validate_document(raw: bytes, *, kind: str, subject_digest: str, version: str) -> None:
    """Fixed-rule check of one syft SPDX document for one subject.

    The image root must carry its platform manifest digest as SHA-256
    checksum. The wheel and sdist roots are the scanned trees, named after the
    project and the candidate's Python version (syft --source-name and
    --source-version); their bytes are bound by the attestation subject.
    """
    require(kind in KINDS, "unknown SBOM kind")
    require(DIGEST.fullmatch(subject_digest) is not None, "invalid SBOM subject digest")
    require(len(raw) <= SBOM_LIMIT, "oversized SBOM evidence")
    document = parse_json(raw, "SBOM is not valid JSON")
    require(isinstance(document, dict), "SBOM must be a JSON object")
    require(document.get("spdxVersion") == SPDX_VERSION
            and document.get("SPDXID") == "SPDXRef-DOCUMENT", "SBOM is not SPDX 2.3")
    creation = document.get("creationInfo")
    require(isinstance(creation, dict) and isinstance(creation.get("creators"), list)
            and GENERATOR in creation["creators"], "SBOM was not generated by the pinned syft")
    root = _described_root(document)
    packages = document["packages"]
    if kind == "image":
        checksums = root.get("checksums")
        require(root.get("name") == IMAGE and isinstance(checksums, list)
                and {"algorithm": "SHA256", "checksumValue": subject_digest[7:]} in checksums,
                "image SBOM does not describe its platform manifest")
    else:
        require(root.get("name") == PROJECT and root.get("versionInfo") == version,
                "package SBOM root does not name the candidate")
    # A document listing nothing but its root says nothing about the artifact.
    require(len(packages) > 1, "SBOM lists no components")


def platform_manifests(index_raw: bytes) -> dict[str, str]:
    """{platform: manifest digest} of an image index, attestation entries excluded."""
    index = parse_json(index_raw, "image index is not valid JSON")
    require(isinstance(index, dict) and index.get("schemaVersion") == 2
            and index.get("mediaType", OCI_INDEX[0]) in OCI_INDEX
            and isinstance(index.get("manifests"), list), "not an image index")
    result: dict[str, str] = {}
    for entry in index["manifests"]:
        require(isinstance(entry, dict) and isinstance(entry.get("platform"), dict)
                and isinstance(entry.get("digest"), str)
                and DIGEST.fullmatch(entry["digest"]) is not None, "invalid index entry")
        platform = entry["platform"]
        if platform.get("os") == "unknown" and platform.get("architecture") == "unknown":
            continue  # buildx attestation manifests carry no image
        require(not platform.get("variant"), "unexpected platform variant")
        key = f"{platform.get('os')}/{platform.get('architecture')}"
        require(key not in result, "duplicate platform in image index")
        result[key] = entry["digest"]
    require(set(result) == set(PLATFORMS), "image index platforms differ from the release set")
    return result


def archive_index(archive: Path, image_digest: str) -> bytes:
    """Raw image index of a single-root OCI archive, checked against its digest."""
    require(DIGEST.fullmatch(image_digest) is not None, "invalid image digest")
    name = "blobs/sha256/" + image_digest[7:]
    with tarfile.open(archive) as tar:
        members = [m for m in tar if m.name.removeprefix("./") == name]
        require(len(members) == 1 and members[0].isfile()
                and members[0].size <= INDEX_LIMIT, "image index missing from OCI archive")
        stream = tar.extractfile(members[0])
        require(stream is not None, "image index missing from OCI archive")
        assert stream is not None
        raw = stream.read(INDEX_LIMIT + 1)
    require(sha256(raw) == image_digest[7:], "image index digest mismatch")
    return raw


def expected_subjects(*, wheel: tuple[str, str], sdist: tuple[str, str],
                      manifests: dict[str, str]) -> list[dict[str, str]]:
    """Subjects in fixed order: wheel, sdist, then image platforms."""
    subjects = []
    for kind, (name, digest) in (("wheel", wheel), ("sdist", sdist)):
        require(NAME.fullmatch(name) is not None and HEX.fullmatch(digest) is not None,
                "invalid distribution subject")
        subjects.append({"subject": kind, "subject_name": name,
                         "subject_digest": "sha256:" + digest,
                         "file": document_name(kind, name)})
    for platform in PLATFORMS:
        subjects.append({"subject": "image", "platform": platform, "subject_name": IMAGE,
                         "subject_digest": manifests[platform],
                         "file": document_name("image", platform)})
    return subjects


def describe(directory: Path, *, wheel: tuple[str, str], sdist: tuple[str, str],
             manifests: dict[str, str], version: str) -> list[dict[str, str]]:
    """Validate every expected document in directory and return receipt entries."""
    require(not directory.is_symlink() and directory.is_dir(), "missing SBOM directory")
    entries = []
    for subject in expected_subjects(wheel=wheel, sdist=sdist, manifests=manifests):
        raw = read_bounded(directory / subject["file"], SBOM_LIMIT)
        validate_document(raw, kind=subject["subject"],
                          subject_digest=subject["subject_digest"], version=version)
        entries.append({**subject, "sha256": sha256(raw), "predicate_type": PREDICATE_TYPE,
                        "generator": f"syft {SYFT_VERSION}"})
    require({p.name for p in directory.iterdir()} == {e["file"] for e in entries},
            "unexpected SBOM files")
    return entries


ENTRY_KEYS = {"subject", "subject_name", "subject_digest", "file", "sha256",
              "predicate_type", "generator"}


def validate_entries(entries: object, *, wheel: tuple[str, str] | None = None,
                     sdist: tuple[str, str] | None = None,
                     manifests: dict[str, str] | None = None) -> list[dict[str, str]]:
    """Shape of the receipt's "sboms" list; subjects are checked when given."""
    require(isinstance(entries, list) and len(entries) == 2 + len(PLATFORMS),
            "sboms must list the wheel, the sdist and every image platform")
    assert isinstance(entries, list)
    for entry in entries:
        require(isinstance(entry, dict), "invalid sboms entry")
        keys = ENTRY_KEYS | ({"platform"} if entry.get("subject") == "image" else set())
        require(set(entry) == keys and all(isinstance(v, str) for v in entry.values()),
                "invalid sboms entry")
        require(DIGEST.fullmatch(entry["subject_digest"]) is not None
                and HEX.fullmatch(entry["sha256"]) is not None
                and entry["predicate_type"] == PREDICATE_TYPE
                and entry["generator"] == f"syft {SYFT_VERSION}", "invalid sboms entry")
    kinds = [(e["subject"], e.get("platform")) for e in entries]
    require(kinds == [("wheel", None), ("sdist", None)] + [("image", p) for p in PLATFORMS],
            "sboms entries out of order")
    for entry in entries:
        name = entry["subject_name"] if entry["subject"] != "image" else entry["platform"]
        require(entry["file"] == document_name(entry["subject"], name)
                and (entry["subject"] != "image" or entry["subject_name"] == IMAGE),
                "invalid sboms entry")
    if wheel is not None and sdist is not None and manifests is not None:
        subjects = expected_subjects(wheel=wheel, sdist=sdist, manifests=manifests)
        require([{k: v for k, v in e.items() if k in s} for e, s in zip(entries, subjects,
                                                                         strict=True)]
                == subjects, "sboms subjects differ from the verified artifacts")
    return entries


def verify_candidate(artifacts: Path, provenance: dict[str, Any], *, wheel: tuple[str, str],
                     sdist: tuple[str, str], archive: Path, image_digest: str,
                     version: str) -> tuple[dict[str, Path], list[dict[str, str]]]:
    """Stage two: bind the stage-one documents to the verified artifacts.

    A receipt without "sboms" (a candidate built by an rc-build.yml that
    predates SBOMs) must also have no SBOM directory; promotion refuses it.
    """
    directory = artifacts / SBOM_DIR
    if "sboms" not in provenance:
        require(not directory.exists() and not directory.is_symlink(),
                "SBOM directory without sboms receipt")
        return {}, []
    manifests = platform_manifests(archive_index(archive, image_digest))
    entries = validate_entries(provenance["sboms"], wheel=wheel, sdist=sdist,
                               manifests=manifests)
    require(not directory.is_symlink() and directory.is_dir(), "missing SBOM directory")
    files: dict[str, Path] = {}
    for entry in entries:
        path = directory / entry["file"]
        raw = read_bounded(path, SBOM_LIMIT)
        require(path.resolve().parent == directory.resolve(), "SBOM escaped its directory")
        require(sha256(raw) == entry["sha256"], "SBOM hash mismatch")
        validate_document(raw, kind=entry["subject"], subject_digest=entry["subject_digest"],
                          version=version)
        files[entry["file"]] = path
    require({p.name for p in directory.iterdir()} == set(files), "unexpected SBOM files")
    return files, entries


def plan(provenance: dict[str, Any], candidate: Path, index_raw: bytes
         ) -> list[tuple[str, Path, str]]:
    """Promotion: every SBOM is required, stored, intact and names the promoted index."""
    require(isinstance(provenance, dict) and "sboms" in provenance,
            "candidate has no SBOM evidence; build a new candidate")
    receipt = provenance.get("candidate")
    image_digest = provenance.get("image_digest")
    require(isinstance(receipt, dict) and isinstance(image_digest, str)
            and DIGEST.fullmatch(image_digest) is not None, "invalid candidate provenance")
    assert isinstance(receipt, dict) and isinstance(image_digest, str)
    require(sha256(index_raw) == image_digest[7:], "registry index differs from the candidate")
    manifests = platform_manifests(index_raw)
    entries = validate_entries(
        provenance["sboms"], manifests=manifests,
        wheel=(str(receipt.get("wheel")), str(receipt.get("wheel_sha256"))),
        sdist=(str(receipt.get("sdist")), str(receipt.get("sdist_sha256"))))
    version = provenance.get("python_version")
    require(isinstance(version, str), "invalid candidate provenance")
    lines = []
    for entry in entries:
        path = candidate / entry["file"]
        raw = read_bounded(path, SBOM_LIMIT)
        require(sha256(raw) == entry["sha256"], "stored SBOM differs from the candidate record")
        validate_document(raw, kind=entry["subject"], subject_digest=entry["subject_digest"],
                          version=str(version))
        if entry["subject"] == "image":
            subject = f"oci://{IMAGE}@{entry['subject_digest']}"
        else:
            subject = str(candidate / entry["subject_name"])
            require(sha256(read_bounded(Path(subject), 1 << 30))
                    == entry["subject_digest"][7:], "candidate file differs from its SBOM subject")
        lines.append((subject, path, entry["subject_digest"]))
    return lines


def match(attestations: object, document: bytes, subject_digest: str) -> None:
    """One verified statement must name the subject and carry the stored document."""
    require(DIGEST.fullmatch(subject_digest) is not None, "invalid SBOM subject digest")
    expected = parse_json(document, "SBOM is not valid JSON")
    require(isinstance(attestations, list) and len(attestations) > 0,
            "no verified SBOM attestation")
    assert isinstance(attestations, list)
    for item in attestations:
        statement = (item.get("verificationResult") or {}).get("statement") \
            if isinstance(item, dict) else None
        if not isinstance(statement, dict) or statement.get("predicateType") != PREDICATE_TYPE:
            continue
        subjects = statement.get("subject")
        named = isinstance(subjects, list) and any(
            isinstance(s, dict) and isinstance(s.get("digest"), dict)
            and s["digest"].get("sha256") == subject_digest[7:] for s in subjects)
        if named and statement.get("predicate") == expected:
            return
    raise ValueError("no verified SBOM attestation carries the stored document")


def embed(provenance_path: Path, directory: Path, archive: Path) -> list[dict[str, str]]:
    """Stage one: add the "sboms" receipt to the finalized candidate provenance."""
    payload = parse_json(read_bounded(provenance_path, 1024 * 1024), "invalid provenance")
    require(isinstance(payload, dict) and "sboms" not in payload, "invalid provenance")
    receipt, image_digest = payload.get("candidate"), payload.get("image_digest")
    version = payload.get("python_version")
    require(isinstance(receipt, dict) and isinstance(image_digest, str)
            and isinstance(version, str), "invalid provenance")
    assert isinstance(receipt, dict) and isinstance(image_digest, str)
    with archive.open("rb") as stream:
        archive_hash = hashlib.file_digest(stream, "sha256").hexdigest()
    require(archive_hash == payload.get("oci_archive_sha256"),
            "OCI archive differs from provenance")
    manifests = platform_manifests(archive_index(archive, image_digest))
    entries = describe(directory, manifests=manifests, version=str(version),
                       wheel=(str(receipt.get("wheel")), str(receipt.get("wheel_sha256"))),
                       sdist=(str(receipt.get("sdist")), str(receipt.get("sdist_sha256"))))
    payload["sboms"] = entries
    temporary = provenance_path.with_suffix(provenance_path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(provenance_path)
    return entries


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    embed_parser = commands.add_parser("embed")
    embed_parser.add_argument("--provenance", required=True, type=Path)
    embed_parser.add_argument("--sbom-dir", required=True, type=Path)
    embed_parser.add_argument("--oci-archive", required=True, type=Path)
    plan_parser = commands.add_parser("plan")
    plan_parser.add_argument("--provenance", required=True, type=Path)
    plan_parser.add_argument("--candidate", required=True, type=Path)
    plan_parser.add_argument("--image-index", required=True, type=Path)
    match_parser = commands.add_parser("match")
    match_parser.add_argument("--attestations", required=True, type=Path)
    match_parser.add_argument("--sbom", required=True, type=Path)
    match_parser.add_argument("--subject-digest", required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == "embed":
            embed(args.provenance, args.sbom_dir, args.oci_archive)
        elif args.command == "plan":
            provenance = parse_json(read_bounded(args.provenance, 1024 * 1024),
                                    "invalid candidate provenance")
            raw = read_bounded(args.image_index, INDEX_LIMIT)
            for subject, path, digest in plan(provenance, args.candidate, raw):
                require(" " not in subject and " " not in str(path), "unsafe plan entry")
                print(subject, path, digest)
        else:
            attestations = parse_json(read_bounded(args.attestations, ATTESTATION_LIMIT),
                                      "unreadable attestation output")
            match(attestations, read_bounded(args.sbom, SBOM_LIMIT), args.subject_digest)
    except (ValueError, OSError, tarfile.TarError) as error:
        message = str(error) if isinstance(error, ValueError) else type(error).__name__
        print(f"SBOM evidence refused: {re.sub(r'[^ -~]', '?', message)[:300]}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
